/**
 * BIRD_SPRITES[id][facing][pose], facing 'left'/'right', pose 'perched'/'flap'.
 * BIRD_SPRITES[id].silhouette is the perched bird in one flat color, for the
 * journal's not-yet-photographed entries.
 */
const SILHOUETTE = new Proxy({}, { get: (_, c) => (c === '.' ? null : '#b8b0a0') });

export const BIRD_SPRITES = {};
for (const [id, bird] of Object.entries(BIRDS)) {
  const shape = SHAPES[bird.shape];
  if (!shape) throw new Error(`bird "${id}": unknown shape "${bird.shape}" (see SHAPES in assets/birds.js)`);
  const { body, wing, belly, head = body, face = head, bill = PALETTE.f } = bird.colors;
  const palette = { ...PALETTE, 1: body, 2: wing, 3: belly, 4: head, 5: face, 6: bill };
  const make = (art, name) => makeSprite(art, palette, `bird "${id}" ${name}`);
  BIRD_SPRITES[id] = {
    right: { perched: make(shape.perched, 'perched'), flap: make(shape.flap, 'flap') },
    left: { perched: make(mirror(shape.perched), 'perched'), flap: make(mirror(shape.flap), 'flap') },
    silhouette: makeSprite(shape.perched, SILHOUETTE, `bird "${id}" silhouette`),
  };
}
