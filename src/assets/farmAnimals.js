// The farm animals: the grandparents' horse, the goats and the chickens. They
// wander their pens like Hannah's puppies (scenes/npcs.js), in the same sprite
// shape as DOG_SPRITES: `sitting` faces you, `left`/`right` are a two-step walk.
//
// The art is just the filled-in animal: outline() draws the black edge around
// it. '1' is the coat, '2' its shade, '3' the mane, tail, beard or comb, '4'
// hooves, horns, beak and feet, '5' the muzzle; each animal fills those in below.
import { PALETTE } from './palette.js';
import { makeSprite, mirror } from '../gfx/sprite.js';

/** Draw a black outline on every empty pixel next to the animal, and drop empty rows under its feet. */
function outline(rows) {
  const filled = (x, y) => rows[y]?.[x] !== undefined && rows[y][x] !== '.';
  const out = rows.map((r, y) => [...r].map((c, x) => {
    if (c !== '.') return c;
    return filled(x - 1, y) || filled(x + 1, y) || filled(x, y - 1) || filled(x, y + 1) ? 'k' : '.';
  }).join(''));
  while (!/[^.]/.test(out[out.length - 1])) out.pop();
  return out;
}

