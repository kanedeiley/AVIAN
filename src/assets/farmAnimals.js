/** ANIMAL_SPRITES[id].sitting, and ANIMAL_SPRITES[id].left / .right: [step A, step B]. */
export const ANIMAL_SPRITES = {};
for (const [id, a] of Object.entries(ANIMALS)) {
  const [coat, shade, mane, hoof, muzzle = coat] = a.colors;
  const palette = { ...PALETTE, 1: coat, 2: shade, 3: mane, 4: hoof, 5: muzzle };
  const make = (art, name) => makeSprite(outline(art), palette, `animal '${id}' ${name}`);
  ANIMAL_SPRITES[id] = {
    sitting: make(a.sitting, 'sitting'),
    right: a.walk.map((art, i) => make(art, `walk ${i}`)),
    left: a.walk.map((art, i) => make(mirror(art), `walk ${i}`)),
  };
}
